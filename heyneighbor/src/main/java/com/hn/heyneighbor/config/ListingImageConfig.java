
package com.hn.heyneighbor.config;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.MediaType;
import org.springframework.http.HttpHeaders;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RestController;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.UUID;

@RestController
public class ListingImageConfig {

    private final Path uploadDirectory;

    public ListingImageConfig(@Value("${app.upload.dir}") String uploadDir) {
        this.uploadDirectory = Path.of(uploadDir).toAbsolutePath().normalize();
    }

    @GetMapping("/listing-uploads/{filename}")
    public ResponseEntity<byte[]> getImage(@PathVariable String filename)
            throws IOException {

        // Only allow the filenames generated by ListingImageService.
        if (!filename.matches(
                "[0-9a-fA-F-]{36}\\.(jpg|png|webp)")) {
            return ResponseEntity.badRequest().build();
        }

        String id = filename.substring(0, 36);
        try {
            UUID.fromString(id);
        } catch (IllegalArgumentException e) {
            return ResponseEntity.badRequest().build();
        }

        Path image = uploadDirectory.resolve(filename).normalize();

        if (!image.startsWith(uploadDirectory)
                || !Files.isRegularFile(image)) {
            return ResponseEntity.notFound().build();
        }

        MediaType type = filename.endsWith(".png")
                ? MediaType.IMAGE_PNG
                : filename.endsWith(".webp")
                ? MediaType.parseMediaType("image/webp")
                : MediaType.IMAGE_JPEG;

        return ResponseEntity.ok()
                .header("X-Content-Type-Options", "nosniff")
                .contentType(type)
                .body(Files.readAllBytes(image));
    }
}
